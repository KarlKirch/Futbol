-- CrossFit professional features: training templates and trainer announcements.

create table if not exists public.wod_training_templates (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(trim(name)) between 1 and 60),
  title text not null default 'CrossFit' check (char_length(trim(title)) between 1 and 80),
  duration_minutes integer not null default 60 check (duration_minutes between 15 and 240),
  capacity integer not null default 12 check (capacity between 1 and 100),
  cancellation_hours integer not null default 4 check (cancellation_hours between 0 and 72),
  workout text,
  note text,
  active boolean not null default true,
  created_by uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.wod_training_templates enable row level security;

create index if not exists wod_training_templates_created_by_idx
  on public.wod_training_templates(created_by);

drop policy if exists wod_training_templates_trainer_select on public.wod_training_templates;
create policy wod_training_templates_trainer_select
on public.wod_training_templates for select
to authenticated
using (
  (select private.wod_is_active_user())
  and (select private.wod_is_trainer())
);

drop policy if exists wod_training_templates_trainer_insert on public.wod_training_templates;
create policy wod_training_templates_trainer_insert
on public.wod_training_templates for insert
to authenticated
with check (
  (select private.wod_is_active_user())
  and (select private.wod_is_trainer())
  and created_by=(select auth.uid())
);

drop policy if exists wod_training_templates_trainer_update on public.wod_training_templates;
create policy wod_training_templates_trainer_update
on public.wod_training_templates for update
to authenticated
using (
  (select private.wod_is_active_user())
  and (select private.wod_is_trainer())
)
with check (
  (select private.wod_is_active_user())
  and (select private.wod_is_trainer())
);

drop policy if exists wod_training_templates_trainer_delete on public.wod_training_templates;
create policy wod_training_templates_trainer_delete
on public.wod_training_templates for delete
to authenticated
using (
  (select private.wod_is_active_user())
  and (select private.wod_is_trainer())
);

revoke all on public.wod_training_templates from anon;
grant select,insert,update,delete on public.wod_training_templates to authenticated;
grant usage,select on sequence public.wod_training_templates_id_seq to authenticated;

create table if not exists public.wod_announcements (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(trim(title)) between 1 and 80),
  body text not null check (char_length(trim(body)) between 1 and 500),
  scope text not null check (scope in ('all','training','waitlist')),
  training_id bigint references public.wod_trainings(id) on delete set null,
  recipient_count integer not null default 0 check (recipient_count >= 0),
  created_by uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

alter table public.wod_announcements enable row level security;

create index if not exists wod_announcements_created_by_idx
  on public.wod_announcements(created_by);
create index if not exists wod_announcements_training_id_idx
  on public.wod_announcements(training_id);

drop policy if exists wod_announcements_trainer_select on public.wod_announcements;
create policy wod_announcements_trainer_select
on public.wod_announcements for select
to authenticated
using (
  (select private.wod_is_active_user())
  and (select private.wod_is_trainer())
);

revoke all on public.wod_announcements from anon;
revoke insert,update,delete on public.wod_announcements from authenticated;
grant select on public.wod_announcements to authenticated;

alter table public.wod_notifications
  drop constraint if exists wod_notifications_kind_check;

alter table public.wod_notifications
  add constraint wod_notifications_kind_check
  check (kind in (
    'training_reminder',
    'waitlist_promoted',
    'training_cancelled',
    'training_changed',
    'training_full',
    'trainer_announcement'
  ));

create or replace function public.wod_send_announcement(
  p_title text,
  p_body text,
  p_scope text default 'all',
  p_training_id bigint default null
)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  caller uuid := (select auth.uid());
  ann_id bigint;
  recipient_total integer := 0;
begin
  if caller is null or coalesce((select (auth.jwt()->>'is_anonymous')::boolean),true) then
    raise exception 'CrossFit nõuab e-posti kontoga sisselogimist';
  end if;

  if not private.wod_is_active_user() or not private.wod_is_trainer() then
    raise exception 'Ainult aktiivne treener saab teadaandeid saata';
  end if;

  if nullif(trim(p_title),'') is null or char_length(trim(p_title))>80 then
    raise exception 'Pealkiri peab olema 1–80 tähemärki';
  end if;

  if nullif(trim(p_body),'') is null or char_length(trim(p_body))>500 then
    raise exception 'Teade peab olema 1–500 tähemärki';
  end if;

  if p_scope not in ('all','training','waitlist') then
    raise exception 'Vigane sihtrühm';
  end if;

  if p_scope in ('training','waitlist') then
    if p_training_id is null or not exists(
      select 1 from public.wod_trainings where id=p_training_id
    ) then
      raise exception 'Vali treening';
    end if;
  else
    p_training_id := null;
  end if;

  insert into public.wod_announcements(
    title,body,scope,training_id,recipient_count,created_by
  )
  values(trim(p_title),trim(p_body),p_scope,p_training_id,0,caller)
  returning id into ann_id;

  if p_scope='all' then
    insert into public.wod_notifications(
      user_id,training_id,kind,title,body,url,tag,dedupe_key,due_at
    )
    select
      p.user_id,null,'trainer_announcement',trim(p_title),trim(p_body),
      'https://karlkirch.github.io/Crossfit/',
      'crossfit-announcement-'||ann_id,
      'announcement:'||ann_id||':'||p.user_id,
      now()
    from public.wod_profiles p
    where p.role='client'
      and not exists(select 1 from public.wod_removed_clients rc where rc.user_id=p.user_id)
    on conflict(dedupe_key) do nothing;

  elsif p_scope='training' then
    insert into public.wod_notifications(
      user_id,training_id,kind,title,body,url,tag,dedupe_key,due_at
    )
    select distinct
      r.user_id,p_training_id,'trainer_announcement',trim(p_title),trim(p_body),
      'https://karlkirch.github.io/Crossfit/',
      'crossfit-announcement-'||ann_id,
      'announcement:'||ann_id||':'||r.user_id,
      now()
    from public.wod_registrations r
    where r.training_id=p_training_id
      and r.status in ('confirmed','waitlist')
      and not exists(select 1 from public.wod_removed_clients rc where rc.user_id=r.user_id)
    on conflict(dedupe_key) do nothing;

  else
    insert into public.wod_notifications(
      user_id,training_id,kind,title,body,url,tag,dedupe_key,due_at
    )
    select distinct
      r.user_id,p_training_id,'trainer_announcement',trim(p_title),trim(p_body),
      'https://karlkirch.github.io/Crossfit/',
      'crossfit-announcement-'||ann_id,
      'announcement:'||ann_id||':'||r.user_id,
      now()
    from public.wod_registrations r
    where r.training_id=p_training_id
      and r.status='waitlist'
      and not exists(select 1 from public.wod_removed_clients rc where rc.user_id=r.user_id)
    on conflict(dedupe_key) do nothing;
  end if;

  get diagnostics recipient_total = row_count;

  update public.wod_announcements
  set recipient_count=recipient_total
  where id=ann_id;

  return recipient_total;
end;
$$;

revoke execute on function public.wod_send_announcement(text,text,text,bigint)
from public,anon;
grant execute on function public.wod_send_announcement(text,text,text,bigint)
to authenticated;
