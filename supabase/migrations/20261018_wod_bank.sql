-- CrossFit private WOD bank.
-- Stores trainer-only WOD metadata and original photos in a private Storage bucket.

create table if not exists public.wod_bank_entries (
  id bigint generated by default as identity primary key,
  source_date date,
  title text not null default 'WOD' check (char_length(trim(title)) between 1 and 120),
  image_path text not null unique,
  draft_text text,
  workout_text text,
  status text not null default 'pending' check (status in ('pending','review','ready')),
  created_by uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.wod_bank_entries enable row level security;

create index if not exists wod_bank_entries_created_by_idx on public.wod_bank_entries(created_by);
create index if not exists wod_bank_entries_status_idx on public.wod_bank_entries(status);
create index if not exists wod_bank_entries_created_at_idx on public.wod_bank_entries(created_at desc);

drop policy if exists wod_bank_entries_trainer_select on public.wod_bank_entries;
create policy wod_bank_entries_trainer_select
on public.wod_bank_entries for select
to authenticated
using ((select private.wod_is_active_user()) and (select private.wod_is_trainer()));

drop policy if exists wod_bank_entries_trainer_insert on public.wod_bank_entries;
create policy wod_bank_entries_trainer_insert
on public.wod_bank_entries for insert
to authenticated
with check (
  (select private.wod_is_active_user())
  and (select private.wod_is_trainer())
  and created_by=(select auth.uid())
);

drop policy if exists wod_bank_entries_trainer_update on public.wod_bank_entries;
create policy wod_bank_entries_trainer_update
on public.wod_bank_entries for update
to authenticated
using ((select private.wod_is_active_user()) and (select private.wod_is_trainer()))
with check (
  (select private.wod_is_active_user())
  and (select private.wod_is_trainer())
  and created_by=(select auth.uid())
);

drop policy if exists wod_bank_entries_trainer_delete on public.wod_bank_entries;
create policy wod_bank_entries_trainer_delete
on public.wod_bank_entries for delete
to authenticated
using ((select private.wod_is_active_user()) and (select private.wod_is_trainer()));

revoke all on public.wod_bank_entries from anon;
grant select,insert,update,delete on public.wod_bank_entries to authenticated;
grant usage,select on sequence public.wod_bank_entries_id_seq to authenticated;

insert into storage.buckets (id,name,public,file_size_limit,allowed_mime_types)
values (
  'wod-bank','wod-bank',false,26214400,
  array['image/jpeg','image/png','image/webp','image/heic','image/heif']::text[]
)
on conflict (id) do update
set public=false,
    file_size_limit=excluded.file_size_limit,
    allowed_mime_types=excluded.allowed_mime_types;

drop policy if exists wod_bank_storage_select_trainer on storage.objects;
create policy wod_bank_storage_select_trainer
on storage.objects for select
to authenticated
using (
  bucket_id='wod-bank'
  and (select private.wod_is_active_user())
  and (select private.wod_is_trainer())
);

drop policy if exists wod_bank_storage_insert_trainer on storage.objects;
create policy wod_bank_storage_insert_trainer
on storage.objects for insert
to authenticated
with check (
  bucket_id='wod-bank'
  and (select private.wod_is_active_user())
  and (select private.wod_is_trainer())
  and (owner=(select auth.uid()) or owner_id=(select auth.uid()::text))
);

drop policy if exists wod_bank_storage_update_trainer on storage.objects;
create policy wod_bank_storage_update_trainer
on storage.objects for update
to authenticated
using (
  bucket_id='wod-bank'
  and (select private.wod_is_active_user())
  and (select private.wod_is_trainer())
)
with check (
  bucket_id='wod-bank'
  and (select private.wod_is_active_user())
  and (select private.wod_is_trainer())
);

drop policy if exists wod_bank_storage_delete_trainer on storage.objects;
create policy wod_bank_storage_delete_trainer
on storage.objects for delete
to authenticated
using (
  bucket_id='wod-bank'
  and (select private.wod_is_active_user())
  and (select private.wod_is_trainer())
);
